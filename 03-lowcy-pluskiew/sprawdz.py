def odkoduj(tekst):
    dane = base64.b64decode(tekst)
    return bytes(b ^ _KLUCZ[i % len(_KLUCZ)] for i, b in enumerate(dane)).decode("utf-8")


def uruchom_testy(baza, nazwa, zrodlo_punktow):
    """Uruchamia testy ucznia na podanej wersji punkty.py; zwraca słownik z wynikami."""
    katalog = baza / nazwa
    katalog.mkdir()
    (katalog / "punkty.py").write_text(zrodlo_punktow, encoding="utf-8")
    shutil.copyfile(TESTY, katalog / "test_punkty.py")
    (katalog / "_straznik_lowca.py").write_text(URUCHAMIACZ, encoding="utf-8")
    raport = katalog / "_raport.json"
    wynik = straznik.uruchom([sys.executable, katalog / "_straznik_lowca.py", katalog, raport], katalog,
                             limit=LIMIT)
    if wynik.czas_minal:
        return {"czas": True}
    try:
        return json.loads(raport.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"awaria": straznik.opisz_przebieg(wynik, katalog, LIMIT) or "testy nie dały wyniku"}


def krotka_nazwa(identyfikator):
    return ".".join(identyfikator.split(".")[-2:])


def main():
    raport = straznik.Raport("ŁOWCY PLUSKIEW (ćwiczenie 03)")
    if not TESTY.is_file():
        raport.popraw("test_punkty.py", ["nie ma pliku test_punkty.py (przywróć go: git checkout -- test_punkty.py)"])
        return raport.koniec("")
    skladnia = straznik.blad_skladni(TESTY)
    if skladnia:
        raport.popraw("test_punkty.py", [skladnia])
        return raport.koniec("")

    with tempfile.TemporaryDirectory(prefix="straznik-03-") as tmp:
        baza = Path(tmp)
        wynik = uruchom_testy(baza, "poprawny", odkoduj(POPRAWNY))
        braki = []
        if wynik.get("czas"):
            braki.append(f"testy nie skończyły się w {LIMIT} s - czy któryś nie czeka na input() albo nie ma "
                         "pętli bez końca?")
        elif wynik.get("awaria"):
            braki.append(wynik["awaria"])
        elif wynik["import"]:
            braki.append("nie da się zaimportować test_punkty.py: "
                         + straznik.opisz_blad(wynik["import"], baza / "poprawny"))
        elif wynik["uruchomione"] == 0:
            braki.append("nie znalazłem żadnego testu - metody muszą mieć nazwy zaczynające się od test_ "
                         "i leżeć w klasie dziedziczącej po unittest.TestCase")
        else:
            for identyfikator, powod in wynik["porazki"] + wynik["bledy"]:
                braki.append(f"{krotka_nazwa(identyfikator)}: {powod}")
            if braki:
                braki.append("Te testy nie przechodzą na poprawnym punkty.py, więc oczekują czegoś innego niż "
                             "specyfikacja. Porównaj oczekiwany wynik z docstringiem funkcji.")
        if braki:
            raport.popraw("testy na poprawnym punkty.py", braki)
            raport.czeka(f"łapanie pluskiew (najpierw wszystkie testy muszą przechodzić na poprawnym kodzie)")
            return raport.koniec("")
        raport.ok(f"testy na poprawnym punkty.py: uruchomionych {wynik['uruchomione']}, wszystkie przechodzą")

        zywe = []
        for nr, (funkcja, podpowiedz, kod) in enumerate(PLUSKWY, start=1):
            wynik = uruchom_testy(baza, f"pluskwa-{nr}", odkoduj(kod))
            zlapana = (wynik.get("czas") or wynik.get("awaria") or wynik.get("import")
                       or wynik.get("porazki") or wynik.get("bledy"))
            if not zlapana:
                zywe.append(f"pluskwa {nr} przeżyła ({funkcja}): {podpowiedz}")
        opis = f"Złapane pluskwy: {len(PLUSKWY) - len(zywe)}/{len(PLUSKWY)}"
        raport.etap(opis, zywe)
    return raport.koniec(f"Wszystkie {len(PLUSKWY)} pluskiew złapane. Od teraz każda zmiana w punkty.py, która łamie "
                         "specyfikację, zapali się na czerwono w python3 -m unittest - zanim zobaczy ją gracz.")


if __name__ == "__main__":
    sys.exit(main())
